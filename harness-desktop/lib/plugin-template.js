const { SAFE_PERMISSION_NAMES, PACKAGE_NAME_PATTERN, SEMVER_PATTERN } = require('./plugin-validator');

// Kept in the same module as the limits it documents so the guide cannot drift
// from what the receiver actually enforces.
const MAX_ARCHIVE_ENTRIES = 5000;
const MAX_UNCOMPRESSED_MIB = 512;

const EXAMPLE_MANIFEST = {
  name: 'dsh-my-plugin',
  version: '1.0.0',
  private: true,
  type: 'module',
  main: 'index.js',
  scripts: { build: 'node build.js' },
  dsh: { bundle: { patch: './cordis.patch.yml' } },
  harnessDesktop: { permissions: ['workspace'] },
};

const EXAMPLE_PATCH = [
  '# Applied after every bundle layer. A top-level YAML array of loader entries.',
  '- insert:',
  '    - id: dsh-my-plugin',
  '      name: dsh-my-plugin',
  '',
].join('\n');

const EXAMPLE_INDEX = [
  "export const name = 'dsh-my-plugin';",
  '',
  '// Cordis entry point. `ctx` is the plugin context; declare anything you read',
  "// from it in `inject`, or the engine throws at boot and the whole tree fails.",
  'export const inject = [];',
  '',
  'export function apply(ctx) {',
  "  ctx.logger?.info?.('dsh-my-plugin loaded');",
  '}',
  '',
].join('\n');

const EXAMPLE_BUILD = [
  '// Runs after dependency install and before activation.',
  '// A non-zero exit fails the install and the live profile is never touched.',
  'process.exit(0);',
  '',
].join('\n');

function guideText() {
  return [
    'HARNESS DESKTOP — PLUGIN FORMAT',
    '===============================',
    '',
    'A plugin is a ZIP archive. Everything below is enforced by the receiver, so an',
    'archive that satisfies this file will be accepted.',
    '',
    '',
    '1. ARCHIVE LAYOUT',
    '-----------------',
    'The ZIP must contain exactly ONE plugin root: a directory holding package.json,',
    'or package.json at the top level. Two candidate roots is an error, and so is none.',
    '',
    '    my-plugin.zip',
    '      └── my-plugin/',
    '            ├── package.json        (required)',
    '            ├── cordis.patch.yml    (required — whatever dsh.bundle.patch points at)',
    '            ├── index.js            (your entry point)',
    '            └── build.js            (optional — only if you declare scripts.build)',
    '',
    'Rejected outright:',
    `  · more than ${MAX_ARCHIVE_ENTRIES} entries`,
    `  · more than ${MAX_UNCOMPRESSED_MIB} MiB uncompressed`,
    '  · absolute paths, or any entry escaping the archive root ("..")',
    '',
    '',
    '2. package.json',
    '---------------',
    'Required fields:',
    '',
    '  name              npm-style package name, 214 characters or fewer.',
    `                    Must match ${PACKAGE_NAME_PATTERN}`,
    '                    Scoped names are fine: @your-scope/dsh-my-plugin',
    '',
    '  version           A semantic version, 128 characters or fewer.',
    `                    Must match ${SEMVER_PATTERN}`,
    '                    Pre-release and build metadata are accepted: 1.2.0-beta.1',
    '',
    '  dsh.bundle.patch  Relative path to your patch file, inside the plugin.',
    '                    The file must exist and be a regular file.',
    '                    Absolute paths and paths starting with ".." are rejected.',
    '',
    'Optional fields:',
    '',
    '  scripts.build     If present it must be a non-empty string. It runs after',
    '                    dependency installation. A non-zero exit fails the install.',
    '',
    '  harnessDesktop.permissions',
    '                    Array of strings, shown on the review screen before you',
    '                    activate. Recognised values:',
    `                      ${[...SAFE_PERMISSION_NAMES].join(', ')}`,
    '                    Anything else is kept but flagged as an unknown declaration.',
    '                    This metadata is descriptive only — it does NOT sandbox the',
    '                    plugin. A plugin is trusted executable code.',
    '',
    'Example:',
    '',
    JSON.stringify(EXAMPLE_MANIFEST, null, 2).split('\n').map((l) => `    ${l}`).join('\n'),
    '',
    '',
    '3. THE PATCH FILE',
    '-----------------',
    'A top-level YAML array of loader patch entries, applied after every bundle layer.',
    'To mount your own plugin, insert it by package name:',
    '',
    EXAMPLE_PATCH.split('\n').map((l) => `    ${l}`).join('\n'),
    '',
    '',
    '4. THE ENTRY POINT',
    '-----------------',
    'Cordis calls apply(ctx). Anything you read off ctx must be listed in `inject`.',
    'Reading an undeclared service throws',
    '    cannot get property "x" without inject',
    'at boot and fails the entire plugin tree — not just your plugin.',
    '',
    EXAMPLE_INDEX.split('\n').map((l) => `    ${l}`).join('\n'),
    '',
    '',
    '5. WHAT HAPPENS WHEN YOU HAND IT OVER',
    '-------------------------------------',
    '  1. Receive     the ZIP is opened and path-checked',
    '  2. Validate    package.json and the declared patch file are checked',
    '  3. Stage       the plugin is copied into managed storage, never the live profile',
    '  4. Install     dependencies are installed with the bundled pnpm',
    '  5. Build       scripts.build runs, if you declared one',
    '  6. Re-validate the built output is checked again',
    '  7. Snapshot    the current working profile is captured first',
    '  8. Activate    dsh plugin add, then the composed config is verified',
    '  9. Health      the engine must start and answer before the change is kept',
    ' 10. Restart     the app restarts and re-verifies; anything failing is rolled back',
    '',
    'At no point is your live profile modified before every check above has passed.',
    'If a step fails, the previous profile is restored automatically.',
    '',
    '',
    '6. COMMON REASONS AN ARCHIVE IS REJECTED',
    '----------------------------------------',
    '  "No package.json found at the plugin root."',
    '      The ZIP nests the plugin too deeply, or ships loose files.',
    '',
    '  "Archive contains multiple possible plugin roots."',
    '      Two or more top-level directories each contain a package.json.',
    '',
    '  "Plugin must declare dsh.bundle.patch in package.json."',
    '      The field is missing, empty, or not a string.',
    '',
    '  "Declared bundle patch does not exist: ..."',
    '      dsh.bundle.patch points at a file that is not in the archive.',
    '',
    '  "package.json \"name\" must be a safe npm-style package name."',
    '      Path separators, spaces, or capitals in the name.',
    '',
    '  "Plugin build failed."',
    '      scripts.build exited non-zero. The live profile was not touched.',
    '',
    '  "cannot get property \"...\" without inject"',
    '      Your apply() read a ctx service without declaring it in `inject`.',
    '',
  ].join('\n');
}

/** Files for a minimal plugin that passes every check, for testing the pipeline. */
function starterFiles(name = 'dsh-starter-plugin') {
  const manifest = {
    ...EXAMPLE_MANIFEST,
    name,
    harnessDesktop: { permissions: ['workspace'] },
  };
  return [
    { path: `${name}/package.json`, content: `${JSON.stringify(manifest, null, 2)}\n` },
    { path: `${name}/cordis.patch.yml`, content: EXAMPLE_PATCH.replace(/dsh-my-plugin/g, name) },
    { path: `${name}/index.js`, content: EXAMPLE_INDEX.replace(/dsh-my-plugin/g, name) },
    { path: `${name}/build.js`, content: EXAMPLE_BUILD },
    { path: `${name}/README.md`, content: `# ${name}\n\nA minimal DSH bundle plugin that passes every Harness Desktop check.\nEdit index.js, then hand this folder back as a ZIP.\n` },
  ];
}

module.exports = { guideText, starterFiles, EXAMPLE_MANIFEST };
